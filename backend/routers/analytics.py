import io
from collections import Counter

from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from sqlmodel import Session, func, select

from models.db import Candidate, JobMatch, get_session

router = APIRouter(prefix="/analytics", tags=["analytics"])


def compute_stats(session: Session) -> dict:
    total_candidates = session.exec(select(func.count()).select_from(Candidate)).one()
    matches = session.exec(select(JobMatch)).all()
    total_matches = len(matches)
    avg_score = pass_rate = 0.0
    if total_matches:
        avg_score = sum(m.match_score for m in matches) / total_matches
        pass_rate = 100 * sum(1 for m in matches if m.qualified) / total_matches
    return {
        "total_candidates": total_candidates,
        "total_matches": total_matches,
        "avg_match_score": round(avg_score, 1),
        "pass_rate": round(pass_rate, 1),
    }


@router.get("/dashboard")
async def get_dashboard_stats(session: Session = Depends(get_session)):
    """Aggregate statistics for the dashboard."""
    return compute_stats(session)


@router.get("/skills")
async def get_skills_distribution(session: Session = Depends(get_session)):
    """The 10 most common skills across all candidates."""
    counts = Counter(skill for c in session.exec(select(Candidate)).all() for skill in c.skills)
    return {"skills": [{"name": name, "count": count} for name, count in counts.most_common(10)]}


@router.get("/export")
async def export_report(session: Session = Depends(get_session)):
    """Download a PDF report of the current dashboard stats."""
    stats = compute_stats(session)

    buffer = io.BytesIO()
    c = canvas.Canvas(buffer, pagesize=letter)
    c.setFont("Helvetica-Bold", 24)
    c.drawString(50, 750, "Recruitment Dashboard Report")
    c.setFont("Helvetica", 14)
    c.drawString(50, 700, f"Total Candidates: {stats['total_candidates']}")
    c.drawString(50, 680, f"Total Matches: {stats['total_matches']}")
    c.drawString(50, 660, f"Average Match Score: {stats['avg_match_score']:.1f}%")
    c.drawString(50, 640, f"Pass Rate: {stats['pass_rate']:.1f}%")
    c.drawString(50, 600, "Generated by AI Recruitment System")
    c.save()
    buffer.seek(0)

    return StreamingResponse(
        buffer,
        media_type="application/pdf",
        headers={"Content-Disposition": "attachment; filename=recruitment_report.pdf"},
    )
